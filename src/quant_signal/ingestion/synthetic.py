"""Deterministic synthetic market data for demos and tests.

Everything this provider returns is SYNTHETIC. Prices are generated from a seeded
one-factor geometric random walk; they are not market prices and carry no information
about any real security. Bars are always tagged with the ``synthetic`` source name.
"""

from __future__ import annotations

import zlib
from collections.abc import Sequence
from datetime import date

import numpy as np
import pandas as pd

from quant_signal.ingestion.models import MarketDataBar, ProviderFetchResult
from quant_signal.ingestion.providers import MarketDataProvider

SYNTHETIC_ANCHOR_DATE = date(2015, 1, 2)
SYNTHETIC_DEFAULT_SEED = 20261116
DEFECT_PREFIX = "BAD"
DEFECT_INVERTED_BAR_DATE = date(2023, 3, 15)
DEFECT_ZERO_CLOSE_DATE = date(2023, 6, 14)
DEFECT_MISSING_WINDOW = (date(2022, 7, 1), date(2022, 10, 31))
SYNTHETIC_DISCLAIMER = "SYNTHETIC DATA: generated by a seeded random walk; not real market prices."


class SyntheticMarketDataProvider(MarketDataProvider):
    """Seeded one-factor random-walk OHLCV generator on a weekday calendar.

    * Every session from ``SYNTHETIC_ANCHOR_DATE`` is generated in order, so the bars
      for any window are identical regardless of the requested start date.
    * Tickers beginning with ``BAD`` receive deliberate, documented defects on fixed
      dates so the data-quality gate can be demonstrated: an inverted high/low bar on
      2023-03-15, a zero close on 2023-06-14, and no bars from 2022-07-01 through
      2022-10-31.
    * The calendar is Monday-Friday without exchange holidays.
    """

    name = "synthetic"

    def __init__(self, seed: int = SYNTHETIC_DEFAULT_SEED) -> None:
        self.seed = seed

    def fetch_daily_bars(
        self,
        symbols: Sequence[str],
        start_date: date,
        end_date: date,
    ) -> ProviderFetchResult:
        """Return synthetic bars for the requested window."""

        sessions = pd.bdate_range(SYNTHETIC_ANCHOR_DATE, end_date)
        if sessions.empty or end_date < start_date:
            return ProviderFetchResult.from_bars([], provider_metadata=self._metadata())
        market_returns = np.random.default_rng(self.seed).normal(0.0003, 0.011, len(sessions))
        in_window = (sessions >= pd.Timestamp(start_date)) & (sessions <= pd.Timestamp(end_date))

        bars: list[MarketDataBar] = []
        defect_symbols: list[str] = []
        for symbol in sorted({symbol.upper() for symbol in symbols}):
            frame = self._symbol_frame(symbol, sessions, market_returns)
            if symbol.startswith(DEFECT_PREFIX):
                frame = self._inject_defects(frame)
                defect_symbols.append(symbol)
            frame = frame[frame.index.isin(sessions[in_window])]
            for row in frame.itertuples(index=True):
                bars.append(
                    MarketDataBar(
                        symbol=symbol,
                        trade_date=pd.Timestamp(row.Index).date(),
                        open=float(row.open),
                        high=float(row.high),
                        low=float(row.low),
                        close=float(row.close),
                        adjusted_close=float(row.close),
                        volume=int(row.volume),
                    )
                )

        warnings = [SYNTHETIC_DISCLAIMER]
        if defect_symbols:
            warnings.append("Deliberate quality defects injected for: " + ", ".join(defect_symbols))
        return ProviderFetchResult.from_bars(
            bars,
            provider_metadata=self._metadata(),
            warnings=warnings,
        )

    def _metadata(self) -> dict[str, object]:
        return {
            "synthetic": True,
            "generator": "one-factor geometric random walk (seeded)",
            "seed": self.seed,
            "anchor_date": SYNTHETIC_ANCHOR_DATE.isoformat(),
            "calendar": "weekdays (no exchange holidays)",
            "defect_prefix": DEFECT_PREFIX,
            "defects": {
                "inverted_high_low": DEFECT_INVERTED_BAR_DATE.isoformat(),
                "zero_close": DEFECT_ZERO_CLOSE_DATE.isoformat(),
                "missing_sessions": [value.isoformat() for value in DEFECT_MISSING_WINDOW],
            },
            "disclaimer": SYNTHETIC_DISCLAIMER,
        }

    def _symbol_frame(
        self,
        symbol: str,
        sessions: pd.DatetimeIndex,
        market_returns: np.ndarray,
    ) -> pd.DataFrame:
        rng = np.random.default_rng([self.seed, zlib.crc32(symbol.encode("utf-8"))])
        count = len(sessions)
        beta = float(rng.uniform(0.6, 1.4))
        idiosyncratic_vol = float(rng.uniform(0.008, 0.02))
        start_price = float(rng.uniform(40.0, 250.0))
        returns = beta * market_returns + rng.normal(0.0, idiosyncratic_vol, count)
        close = start_price * np.exp(np.cumsum(returns))
        previous_close = np.concatenate([[start_price], close[:-1]])
        open_ = previous_close * np.exp(rng.normal(0.0, 0.003, count))
        high = np.maximum(open_, close) * (1.0 + np.abs(rng.normal(0.0, 0.006, count)))
        low = np.minimum(open_, close) * (1.0 - np.abs(rng.normal(0.0, 0.006, count)))
        volume = np.round(rng.lognormal(mean=14.0, sigma=0.35, size=count)).astype(np.int64)
        return pd.DataFrame(
            {
                "open": np.round(open_, 4),
                "high": np.round(high, 4),
                "low": np.round(low, 4),
                "close": np.round(close, 4),
                "volume": volume,
            },
            index=sessions,
        )

    def _inject_defects(self, frame: pd.DataFrame) -> pd.DataFrame:
        defective = frame.copy()
        inverted = pd.Timestamp(DEFECT_INVERTED_BAR_DATE)
        if inverted in defective.index:
            high = defective.at[inverted, "high"]
            defective.at[inverted, "high"] = defective.at[inverted, "low"]
            defective.at[inverted, "low"] = high
        zero_close = pd.Timestamp(DEFECT_ZERO_CLOSE_DATE)
        if zero_close in defective.index:
            defective.at[zero_close, "close"] = 0.0
        gap_start, gap_end = (pd.Timestamp(value) for value in DEFECT_MISSING_WINDOW)
        gap = (defective.index >= gap_start) & (defective.index <= gap_end)
        return defective[~gap]
